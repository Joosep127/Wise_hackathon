await api(host, { action: "lock", revision: state.revision }, 400);
await api(guest, { action: "assign", item: pizza.id, revision: 0, weights: {} }, 403);
await api(host, { action: "assign", item: pizza.id, revision: 0, weights: { [sam.me]: 1, [jo.me]: 3 } });
